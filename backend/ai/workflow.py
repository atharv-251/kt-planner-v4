from typing import TypedDict, Optional, List, Dict, Any
from langgraph.graph import StateGraph, END
from sqlalchemy.orm import Session
from backend.database import SessionLocal
from backend.ai.agents import (
    ProjectProfileAgent,
    KnowledgeGraphAgent,
    KTLevelAgent,
    TopicDecompositionAgent,
    QualityAgent,

)
from backend.services.validation_service import ValidationService

class QualityAgent:
    """Agent 6: Validates generated plan against transition quality and compliance standards."""
    @staticmethod
    def run(db: Session, transition_id: str) -> Dict[str, Any]:
        report = ValidationService.run_full_validation(db, transition_id)
        return {
            "status": "success",
            "quality_status": report.overall_status,
            "quality_score": report.score_percent,
            "passed_checks": report.passed_checks,
            "total_checks": report.total_checks,
            "checks": [c.dict() for c in report.checks],
        }

# LangGraph State Schema
class KTPlannerState(TypedDict):
    transition_id: str
    current_stage: str
    status_message: str
    errors: List[str]

# Graph Node Implementations (Agents inspect & persist directly to SQLite; no plan bloat in graph state)
def node_profile_agent(state: KTPlannerState) -> KTPlannerState:
    db = SessionLocal()
    try:
        ProjectProfileAgent.run(db, state["transition_id"])
        return {
            **state,
            "current_stage": "profile_generated",
            "status_message": "Project Profile extracted and synthesized by Agent 1.",
        }
    except Exception as e:
        return {**state, "errors": state.get("errors", []) + [str(e)]}
    finally:
        db.close()

