def node_quality_agent(state: KTPlannerState) -> KTPlannerState:
    db = SessionLocal()
    try:
        res = QualityAgent.run(db, state["transition_id"])
        return {
            **state,
            "current_stage": "quality_validated",
            "status_message": f"Quality validated by Agent 6 with score {res['quality_score']}%.",
        }
    except Exception as e:
        return {**state, "errors": state.get("errors", []) + [str(e)]}
    finally:
        db.close()

# Build and Compile LangGraph Workflow
def build_kt_planner_workflow():
    workflow = StateGraph(KTPlannerState)

    workflow.add_node("profile_agent", node_profile_agent)
    workflow.add_node("knowledge_graph_agent", node_knowledge_graph_agent)
    workflow.add_node("kt_level_agent", node_kt_level_agent)
    workflow.add_node("decomposition_agent", node_decomposition_agent)
    workflow.add_node("quality_agent", node_quality_agent)

    workflow.set_entry_point("profile_agent")
    workflow.add_edge("profile_agent", "knowledge_graph_agent")
    workflow.add_edge("knowledge_graph_agent", "kt_level_agent")
    workflow.add_edge("kt_level_agent", "decomposition_agent")
    workflow.add_edge("decomposition_agent", "quality_agent")
    workflow.add_edge("quality_agent", END)

    return workflow.compile()

try:
    from agentic_blueprint import wrap
    kt_planner_app = wrap(build_kt_planner_workflow(), risk_class="low", name="KTPlannerWorkflow")
except Exception:
    kt_planner_app = build_kt_planner_workflow()


